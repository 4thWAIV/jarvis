"""One immutable YAML revision behind architecture communication.

SQLite identity and provenance use JARVIS's existing database. Original and
generated bytes use its existing package storage. The upstream renderer's
pinned page-data contract supplies parsed YAML; no local language parser,
checker or renderer competes with the kit.
"""
from __future__ import annotations

import json
import os
import re
import tempfile
import threading
import time
import uuid
from contextlib import closing
from html.parser import HTMLParser
from pathlib import Path

from jarvis import data_paths, language_kit as kit, run_store, work_store

ARCH_CONSTRUCTS = ("forms", "members", "reach", "exactness", "groups", "placement", "relations")
_MIGRATIONS = {1: """
CREATE TABLE language_documents (
    id TEXT PRIMARY KEY, work_id TEXT NOT NULL, created_at REAL NOT NULL
);
CREATE TABLE language_document_revisions (
    document_id TEXT NOT NULL REFERENCES language_documents(id),
    revision TEXT NOT NULL, parent_revision TEXT, created_at REAL NOT NULL,
    source_sha256 TEXT NOT NULL, view_sha256 TEXT, kit_digest TEXT NOT NULL,
    language TEXT NOT NULL, metadata TEXT NOT NULL, check_json TEXT NOT NULL,
    PRIMARY KEY(document_id, revision)
);
CREATE TABLE language_publications (
    document_id TEXT NOT NULL, revision TEXT NOT NULL, archive_sha256 TEXT NOT NULL,
    archive_path TEXT NOT NULL, created_at REAL NOT NULL,
    PRIMARY KEY(document_id, revision),
    FOREIGN KEY(document_id, revision) REFERENCES language_document_revisions(document_id, revision)
);
"""}
_migration_lock = threading.Lock()


class DocumentError(ValueError):
    pass


def _connect():
    connection = run_store._connect()
    with _migration_lock:
        run_store.migrate(connection, "language_document_schema", _MIGRATIONS, "language documents")
        connection.commit()
    return connection


def storage() -> Path:
    return data_paths.packages_dir() / ".language-documents"


def authoring_contract() -> str:
    """The same shipped authoring contract for the brain and internal agents."""
    return (data_paths.PACKAGE_DIR / "language_authoring.md").read_text(encoding="utf-8").strip()


class _PageData(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=False)
        self.blocks: list[str] = []
        self.inside = False

    def handle_starttag(self, tag, attrs):
        fields = dict(attrs)
        if tag == "script" and fields.get("id") == "page-data":
            if fields.get("type") != "application/json":
                raise DocumentError("The upstream page-data block is not JSON.")
            self.inside = True
            self.blocks.append("")

    def handle_data(self, data):
        if self.inside:
            self.blocks[-1] += data

    def handle_endtag(self, tag):
        if tag == "script":
            self.inside = False


def page_data(view: bytes) -> dict:
    parser = _PageData()
    parser.feed(view.decode("utf-8"))
    if len(parser.blocks) != 1:
        raise DocumentError("The pinned upstream renderer must produce exactly one page-data block.")
    body = json.loads(parser.blocks[0])
    if not isinstance(body, dict) or not isinstance(body.get("doc"), dict) or not isinstance(body.get("found"), dict):
        raise DocumentError("The upstream page-data contract changed; update its adapter before publication.")
    return body


def _declarations(document: dict) -> list[str]:
    names = []
    for declaration in document.get("declare", []):
        if not isinstance(declaration, dict):
            continue
        for body in declaration.values():
            if isinstance(body, dict) and isinstance(body.get("id"), str):
                names.append(body["id"])
    return names


def document_title(document: dict) -> str:
    title = document.get("title")
    return title.strip() if isinstance(title, str) and title.strip() else "Architecture document"


def revision_for(document_id: str, source_sha256: str, kit_digest: str, metadata: dict,
                 parent_revision: str | None) -> str:
    return kit.sha256(json.dumps({"document_id": document_id, "source_sha256": source_sha256,
                                "kit_digest": kit_digest, "metadata": metadata,
                                "parent_revision": parent_revision}, sort_keys=True).encode())


def _coverage(document: dict, coverage: dict) -> list[str]:
    problems = []
    if not isinstance(coverage, dict):
        return ["Declare the architecture coverage contract."]
    if set(coverage) - {"constructs", "declarations", "unresolved", "outside_language"}:
        problems.append("The coverage contract has unknown fields.")
    constructs = coverage.get("constructs")
    if not isinstance(constructs, list) or not constructs or any(c not in ARCH_CONSTRUCTS for c in constructs):
        problems.append("Declare supported architecture constructs from capabilities.")
    declared = coverage.get("declarations")
    if not isinstance(declared, list) or not all(isinstance(x, str) for x in declared) or sorted(declared) != sorted(_declarations(document)):
        problems.append("Coverage declarations must name every declaration in this exact source revision.")
    unresolved = coverage.get("unresolved")
    if not isinstance(unresolved, list) or not all(isinstance(x, str) and x.strip() for x in unresolved):
        problems.append("Coverage unresolved must be an explicit list of unfinished portions.")
    elif unresolved:
        problems.append("Unresolved architecture remains a draft: " + "; ".join(unresolved))
    outside = coverage.get("outside_language")
    if not isinstance(outside, list) or not all(isinstance(x, str) and x.strip() for x in outside):
        problems.append("Coverage outside_language must explicitly list meaning outside the enabled language.")
    return problems


def _readable_view(markdown: str | None) -> dict[str, bytes]:
    if markdown is None:
        return {}
    if not isinstance(markdown, str) or not markdown.strip() or len(markdown.encode("utf-8")) > kit.MAX_SOURCE_BYTES:
        raise DocumentError("The author-supplied Markdown must contain text and fit within 1 MiB.")
    return {"UNDERSTANDING.md": markdown.encode("utf-8")}


def _store_bytes(directory: Path, files: dict[str, bytes]) -> None:
    directory.parent.mkdir(parents=True, exist_ok=True)
    if directory.exists():
        if any((directory / name).read_bytes() != body for name, body in files.items()):
            raise DocumentError("Immutable revision bytes differ from their recorded revision.")
        return
    with tempfile.TemporaryDirectory(dir=directory.parent, prefix=".stage-") as name:
        staged = Path(name) / "revision"
        staged.mkdir(mode=0o700)
        for filename, body in files.items():
            (staged / filename).write_bytes(body)
        os.rename(staged, directory)


class Documents:
    def capabilities(self) -> dict:
        installed = None
        try:
            installed = kit.active()
            active = {"version": installed.release.version, "digest": installed.release.digest}
            error = None
        except kit.KitError as problem:
            active, error = None, str(problem)
        return {"active_kit": active, "runtime": {"node_majors": sorted(kit.SUPPORTED_NODE_MAJORS), "platform": "macOS"},
                "languages": {"arch": {"enabled": True, "constructs": list(ARCH_CONSTRUCTS)},
                              "metalang": {"enabled": False, "reason": "Carried by the kit; authoring adoption is staged."},
                              "propose": {"enabled": False, "reason": "Vote mappings require a separate capability adoption review."},
                              "evolang": {"enabled": False, "reason": "Carried by this kit; capability adoption is pending." if installed and (installed.directory / "evolang.yaml").is_file() else "No upstream language file exists."}},
                "observation": "source-only until an upstream renderer observation contract is available",
                "error": error}

    def validate(self, *, source: str, work_id: str, scope_revision: str, author: str,
                 coverage: dict, document_id: str | None = None,
                 parent_revision: str | None = None, evidence: list[str] | None = None,
                 reported_by: str = "", readable_markdown: str | None = None) -> dict:
        if not all(isinstance(x, str) and x.strip() for x in (source, work_id, scope_revision, author)):
            raise DocumentError("A draft needs source, Work linkage, scope revision and author provenance.")
        if work_store.get(work_id) is None:
            raise DocumentError("The linked Work item does not exist.")
        if evidence is not None and (not isinstance(evidence, list) or not all(isinstance(x, str) for x in evidence)):
            raise DocumentError("Evidence must be a list of links; code correspondence is separate from language checking.")
        installed = kit.active()
        raw = source.encode("utf-8")
        checked = installed.run("check", raw)
        rendered = installed.run("render", raw)
        parsed, problems = {}, []
        if rendered.view is not None:
            try:
                parsed = page_data(rendered.view)["doc"]
            except (DocumentError, ValueError) as error:
                problems.append(str(error))
        else:
            problems.append("The upstream renderer could not produce an inspection page.")
        language = parsed.get("language", "metalang")
        if language != "arch":
            problems.append(f"Architecture publication requires language arch; this document names {language!r}.")
        problems.extend(_coverage(parsed, coverage))
        if not checked.ok:
            problems.append("The upstream checker rejected this draft or left unfinished values.")
        readable = _readable_view(readable_markdown)
        metadata = {"title": document_title(parsed), "work_id": work_id, "scope_revision": scope_revision, "author": author, "reported_by": reported_by,
                    "coverage": coverage, "evidence": evidence or [], "status": "proposed",
                    "declarations": _declarations(parsed)}
        if readable:
            metadata["readable"] = {"origin": "author-supplied", "member": "UNDERSTANDING.md", "markdown_sha256": kit.sha256(readable["UNDERSTANDING.md"]),
                                    "meaning": "Derived view of this YAML revision; semantic correspondence requires review."}
        check = {"ok": checked.ok and not problems, "upstream_ok": checked.ok,
                 "exit_code": checked.exit_code, "diagnostics": checked.diagnostics,
                 "render_diagnostics": rendered.diagnostics, "problems": problems, "runtime": checked.runtime,
                 "source_sha256": kit.sha256(raw), "kit_digest": installed.release.digest,
                 "meaning": "Language conformance is separate from code correspondence and human approval."}
        document_id = document_id or "document-" + uuid.uuid4().hex
        if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]{0,100}", document_id):
            raise DocumentError("Document identity must be a plain name of at most 101 characters.")
        revision = revision_for(document_id, check["source_sha256"], installed.release.digest, metadata, parent_revision)
        view = rendered.view
        # The evidence binds both source and projection, even when the page is
        # an invalid draft's inspection view rather than validated architecture.
        check["view_sha256"] = kit.sha256(view) if view else None
        files = {"source.yaml": raw, "check.json": json.dumps(check, sort_keys=True).encode(), **readable}
        if view:
            files["view.html"] = view
        with closing(_connect()) as conn, conn:
            conn.execute("BEGIN IMMEDIATE")
            existing = conn.execute("SELECT * FROM language_documents WHERE id=?", (document_id,)).fetchone()
            if existing is not None:
                if existing["work_id"] != work_id:
                    raise DocumentError("A document cannot move to another Work item.")
                latest = conn.execute("SELECT revision FROM language_document_revisions WHERE document_id=? ORDER BY created_at DESC, rowid DESC LIMIT 1", (document_id,)).fetchone()
                if latest is None or latest["revision"] != parent_revision:
                    raise DocumentError("The source edit is stale; retrieve the current revision before proposing its replacement.")
            elif parent_revision:
                raise DocumentError("A new document has no parent revision.")
            else:
                conn.execute("INSERT INTO language_documents VALUES (?,?,?)", (document_id, work_id, time.time()))
            _store_bytes(storage() / revision, files)
            conn.execute("INSERT OR IGNORE INTO language_document_revisions VALUES (?,?,?,?,?,?,?,?,?,?)",
                         (document_id, revision, parent_revision, time.time(), check["source_sha256"],
                          check["view_sha256"], installed.release.digest, str(language), json.dumps(metadata), json.dumps(check)))
        return self.retrieve(document_id=document_id, revision=revision)

    def retrieve(self, *, document_id: str, revision: str) -> dict:
        with closing(_connect()) as conn:
            row = conn.execute("SELECT r.*, d.work_id FROM language_document_revisions r JOIN language_documents d ON d.id=r.document_id WHERE r.document_id=? AND r.revision=?", (document_id, revision)).fetchone()
            publication = conn.execute("SELECT * FROM language_publications WHERE document_id=? AND revision=?", (document_id, revision)).fetchone()
        if row is None:
            raise DocumentError("The requested document revision does not exist.")
        held = storage() / row["revision"]
        metadata = json.loads(row["metadata"])
        readable = metadata.get("readable", {})
        for filename, expected in (("source.yaml", row["source_sha256"]), ("view.html", row["view_sha256"]),
                                   (readable.get("member", "readable.md"), readable.get("markdown_sha256")), ("readable.pdf", readable.get("pdf_sha256"))):
            if expected and (not (held / filename).is_file() or (held / filename).is_symlink()
                             or kit.sha256((held / filename).read_bytes()) != expected):
                raise DocumentError(f"The stored {filename} no longer matches this revision; publication is blocked.")
        check = json.loads(row["check_json"])
        if json.loads((held / "check.json").read_text()) != check:
            raise DocumentError("The stored check evidence no longer matches this revision.")
        return {"document_id": document_id, "revision": revision, "source_revision": row["source_sha256"],
                "parent_revision": row["parent_revision"], "work_id": row["work_id"],
                "language": row["language"], "kit_digest": row["kit_digest"], "check": check,
                "metadata": metadata, "view_sha256": row["view_sha256"],
                "references": {"source": str(held / "source.yaml"), "check": str(held / "check.json"),
                               "view": str(held / "view.html") if row["view_sha256"] else None,
                               "readable_markdown": str(held / readable.get("member", "readable.md")) if readable else None,
                               "readable_pdf": str(held / "readable.pdf") if readable.get("pdf_sha256") else None},
                "publication": dict(publication) if publication else None}

    def render(self, *, document_id: str, revision: str, source_revision: str) -> dict:
        envelope = self.retrieve(document_id=document_id, revision=revision)
        if envelope["source_revision"] != source_revision:
            raise DocumentError("The requested render belongs to a different source revision.")
        if not envelope["check"]["ok"] or not envelope["view_sha256"]:
            raise DocumentError("This draft has no validated render; inspect its checker diagnostics.")
        kit.active(envelope["kit_digest"])
        return envelope
