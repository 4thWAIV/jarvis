"""JARVIS's one layout spec (presentation_assets/layout-spec.json): the
frame range, the unit rule, the text styles and floors, the picture floor,
the places a picture is drawn and every named layout's boxes. Everything
that draws or proves a deck reads its numbers here, never its own copy:

    python -m jarvis.layout_spec           # write the generated CSS and width table
    python -m jarvis.layout_spec --check   # exit 1 when they differ from the spec

The generated parts are presentation.css's block between GENERATED_BEGIN
and GENERATED_END and font-widths.json (font_metrics); `font_css` is the
bundled font as data URIs, which JARVIS serves once at FONT_PATH (as it
serves the story helper) and every built deck links: no deck carries its
own copy, and one opened outside JARVIS draws in the system font.
"""
from __future__ import annotations

import argparse
import base64
import functools
import json
import sys
from pathlib import Path

from jarvis import font_metrics

ASSETS = Path(__file__).with_name("presentation_assets")
PATH = ASSETS / "layout-spec.json"
CSS = ASSETS / "presentation.css"
# The one place the bundled font reaches a deck: JARVIS serves it here
# (packages_api), and the compiler links it from every deck's page.
FONT_PATH = "/api/packages/presentation-font.css"
GENERATED_BEGIN = "/* layout-spec: generated by python -m jarvis.layout_spec; do not edit */"
GENERATED_END = "/* layout-spec: end */"


@functools.cache
def spec() -> dict:
    return json.loads(PATH.read_text(encoding="utf-8"))


def unit(frame: tuple[float, float]) -> float:
    """One deck unit in pixels at `frame` (width, height)."""
    rule = spec()["unit"]
    return min(frame[0] / rule["width"], frame[1] / rule["height"])


def smallest_unit() -> float:
    return unit(tuple(spec()["frame"]["min"]))


def corners() -> list[tuple[int, int]]:
    """The frame range's four corners, where a deck is proven."""
    (w0, h0), (w1, h1) = spec()["frame"]["min"], spec()["frame"]["max"]
    return [(w0, h0), (w0, h1), (w1, h0), (w1, h1)]


def style_px(style: str, u: float) -> float:
    """A text style's size in px at deck unit `u`: its units, clamped."""
    s = spec()["styles"][style]
    return min(max(s["units"] * u, s["min_px"]), s["max_px"])


def picture_box(role: str, count: int = 1) -> tuple[float, float]:
    """The place, in pixels at the smallest frame, a picture of `role`
    (content, context, compare or option) is drawn in when it is one of
    `count` side by side."""
    place = spec()["pictures"][role]
    count = max(1, min(count, place.get("columns_max", count)))
    gap = place.get("gap", 0)
    width = (place["width"] - gap * (count - 1)) / count - place.get("padding", 0)
    u = smallest_unit()
    return width * u, place["height"] * u


def layouts() -> list[str]:
    return list(spec()["layouts"])


def slots_of(layout: str) -> list[str]:
    named = spec()["layouts"][layout]
    return list(named.get("columns", {}).get("slots", [])) + list(named["slots"])


def boxes(layout: str, filled: set[str]) -> dict[str, tuple[float, float, float, float]]:
    """Every filled slot's box in deck units. A comparison's columns share
    their box by how many are filled."""
    named = spec()["layouts"][layout]
    out = {slot: tuple(box) for slot, box in named["slots"].items() if slot in filled}
    columns = named.get("columns")
    if columns:
        used = [slot for slot in columns["slots"] if slot in filled]
        x, y, w, h = columns["box"]
        gap = columns["gap"]
        each = (w - gap * (len(used) - 1)) / max(1, len(used))
        for n, slot in enumerate(used):
            out[slot] = (x + n * (each + gap), y, each, h)
    return out


def slot_px(box) -> tuple[float, float]:
    """A slot's inner size in px at the smallest frame."""
    return frame_box(box, tuple(spec()["frame"]["min"]))


def frames(steps: int = 6) -> list[tuple[float, float]]:
    """Frames across the whole range the proof checks: a grid with the
    corners, and every frame where the unit switches from width to height."""
    (w0, h0), (w1, h1) = spec()["frame"]["min"], spec()["frame"]["max"]
    rule = spec()["unit"]
    out = {(w0 + (w1 - w0) * i / steps, h0 + (h1 - h0) * j / steps)
           for i in range(steps + 1) for j in range(steps + 1)}
    for i in range(steps + 1):
        w = w0 + (w1 - w0) * i / steps
        if h0 <= w * rule["height"] / rule["width"] <= h1:
            out.add((w, w * rule["height"] / rule["width"]))
    return sorted(out)


# -- narrow frames: one column in reading order ----------------------------------------

def is_narrow(frame: tuple[float, float]) -> bool:
    below = spec()["narrow"]["below"]
    return frame[0] < below[0] or frame[1] < below[1]


def narrow_widths() -> list[float]:
    """The widths a narrow column is proven at: from its least up to the
    widest frame (a short frame of any width draws it), and the widest frame
    narrow by width alone."""
    n = spec()["narrow"]
    least, most = n["min_width"], spec()["frame"]["max"][0]
    steps = n["widths"]
    return sorted({least + (most - least) * i / steps for i in range(steps + 1)} | {n["below"][0] - 1})


def narrow_unit(width: float) -> float:
    return width / spec()["narrow"]["unit"]


def narrow_title_width(width: float) -> float:
    return width - 2 * spec()["narrow"]["margin"] * narrow_unit(width)


def narrow_slot_width(width: float) -> float:
    """A slot's inner width in a narrow column `width` px wide."""
    return narrow_title_width(width) - 2 * spec()["slot_padding"] * narrow_unit(width)


def narrow_height(kind: str, width: float) -> float:
    """The inner height a picture, vector or chart is drawn at in a narrow column."""
    u = narrow_unit(width)
    return (spec()["narrow"]["heights"][kind] - 2 * spec()["slot_padding"]) * u


# -- what is generated ------------------------------------------------------------------

def _length(units: float) -> str:
    return f"calc({units:g} * var(--u))"


def _box(selector: str, box) -> str:
    """A box drawn on the canvas, which is the whole frame: its design-space
    position and size as shares of the frame, so a wider or taller frame
    gives the box the room (frame_box is the same rule in pixels)."""
    x, y, w, h = box
    width, height = spec()["unit"]["width"], spec()["unit"]["height"]
    return (f"{selector} {{ left: {100 * x / width:.4f}%; top: {100 * y / height:.4f}%; "
            f"width: {100 * w / width:.4f}%; height: {100 * h / height:.4f}%; }}")


def frame_box(box, frame: tuple[float, float]) -> tuple[float, float]:
    """A slot's inner width and height in px at `frame`, its padding off."""
    width, height = spec()["unit"]["width"], spec()["unit"]["height"]
    pad = 2 * spec()["slot_padding"] * unit(frame)
    return box[2] / width * frame[0] - pad, box[3] / height * frame[1] - pad


def generated_css() -> str:
    s = spec()
    lines = [GENERATED_BEGIN, ":root {"]
    for name, style in s["styles"].items():
        lines.append(f"  --deck-{name}: clamp({style['min_px']}px, {_length(style['units'])}, "
                     f"{style['max_px']}px);")
        lines.append(f"  --deck-{name}-line: {style['line']:g};")
    lines += ["}",
              ".presentation-canvas { position: absolute; inset: 0; }",
              f".presentation-slot {{ padding: {_length(s['slot_padding'])}; }}",
              _box(".presentation-title", s["title"])]
    for layout, named in s["layouts"].items():
        for slot, box in named["slots"].items():
            lines.append(_box(f'.presentation-slot[data-layout="{layout}"][data-slot="{slot}"]', box))
        columns = named.get("columns")
        if columns:
            for count in range(1, len(columns["slots"]) + 1):
                filled = set(columns["slots"][:count])
                for slot, box in boxes(layout, filled).items():
                    lines.append(_box(f'.presentation-slot[data-layout="{layout}"][data-columns="{count}"]'
                                      f'[data-slot="{slot}"]', box))
    lines += _components_css() + _narrow_css()
    lines.append(GENERATED_END)
    return "\n".join(lines) + "\n"


def _components_css() -> list[str]:
    c = spec()["components"]
    callout, figures, steps = c["callout"], c["figures"], c["steps"]
    return [
        f".presentation-callout {{ border-left: {callout['border_px']}px solid var(--accent); "
        f"padding: {_length(callout['pad'][1])} {_length(callout['pad'][0])}; }}",
        f".presentation-figures {{ display: grid; grid-template-columns: repeat(var(--count), minmax(0, 1fr)); "
        f"gap: {_length(figures['gap'])}; }}",
        f".presentation-figure {{ padding: {_length(figures['pad'][1])} {_length(figures['pad'][0])}; }}",
        f".presentation-figure-value {{ font-size: var(--deck-figure); line-height: var(--deck-figure-line); }}",
        f".presentation-steps {{ display: flex; flex-direction: column; gap: {_length(steps['gap'])}; }}",
        f".presentation-step {{ display: grid; grid-template-columns: {steps['marker']:g}em minmax(0, 1fr); "
        f"column-gap: {steps['marker_gap']:g}em; align-items: start; }}",
        f".presentation-step-marker {{ width: {steps['marker']:g}em; height: {steps['marker']:g}em; }}",
    ]


def _narrow_css() -> list[str]:
    """A narrow frame: the slide one scrolling column in reading order, in
    the narrow unit; presentation.js sets .presentation-narrow below
    narrow.below (read from --narrow-width and --narrow-height)."""
    s, n = spec(), spec()["narrow"]
    at = ".presentation-narrow .presentation-slide"
    sizes = " ".join(f"--deck-{name}: clamp({style['min_px']}px, {_length(style['units'])}, {style['max_px']}px);"
                     for name, style in s["styles"].items())
    # :is() takes its most specific argument's weight, so these beat every wide box.
    each = (f"{at} .presentation-canvas > :is(.presentation-title, .presentation-slot, "
            f".presentation-slot[data-layout][data-slot][data-columns])")
    out = [f":root {{ --narrow-width: {n['below'][0]}; --narrow-height: {n['below'][1]}; }}",
           f"{at} {{ --u: calc(100vw / {n['unit']}); {sizes} overflow-x: hidden; overflow-y: auto; "
           f"scrollbar-width: none; }}",
           f"{at} .presentation-canvas {{ position: relative; inset: auto; box-sizing: border-box; "
           f"min-height: 100%; display: flex; flex-direction: column; gap: {_length(n['gap'])}; "
           f"padding: {_length(n['margin'])}; }}",
           f"{each} {{ position: relative; left: auto; top: auto; width: auto; height: auto; flex: none; }}",
           f"{at} .presentation-figures {{ grid-template-columns: minmax(0, 1fr); }}",
           f"{at} .table :is(thead) {{ display: none; }}",
           f"{at} .table, {at} .table :is(tbody, tr, th, td) {{ display: block; padding: 0; border: 0; }}",
           f"{at} .table tr {{ padding: {_length(s['styles']['cell']['pad'][1])} "
           f"{_length(s['styles']['cell']['pad'][0])}; border-bottom: 1px solid var(--edge); }}",
           f"{at} .table td[data-head]::before {{ content: attr(data-head) \": \"; font-weight: 700; }}"]
    for kind, height in n["heights"].items():
        out.append(f'{each}[data-kind="{kind}"] {{ height: {_length(height)}; }}')
    return out


@functools.lru_cache(maxsize=1)
def font_css() -> str:
    """The bundled font as @font-face rules with data URIs, served at
    FONT_PATH."""
    rules = []
    for face, name in font_metrics.FACES.items():
        data = base64.b64encode((font_metrics.FONT_DIR / name).read_bytes()).decode()
        weight = 700 if face == "bold" else 400
        rules.append(f"@font-face {{ font-family: \"{font_metrics.FAMILY}\"; font-style: normal; "
                     f"font-weight: {weight}; font-display: block; "
                     f"src: url(data:font/ttf;base64,{data}) format(\"truetype\"); }}")
    return "\n".join(rules) + "\n"


def _with_generated(css: str) -> str:
    begin, end = css.index(GENERATED_BEGIN), css.index(GENERATED_END) + len(GENERATED_END) + 1
    return css[:begin] + generated_css() + css[end:]


def _widths() -> str:
    return json.dumps(font_metrics.table(), indent=1, sort_keys=True) + "\n"


def stale() -> list[str]:
    """The generated files that differ from the spec and the font."""
    out = []
    if _with_generated(CSS.read_text(encoding="utf-8")) != CSS.read_text(encoding="utf-8"):
        out.append(str(CSS.relative_to(ASSETS.parent.parent)))
    if not font_metrics.WIDTHS.exists() or font_metrics.WIDTHS.read_text(encoding="utf-8") != _widths():
        out.append(str(font_metrics.WIDTHS.relative_to(ASSETS.parent.parent)))
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m jarvis.layout_spec")
    parser.add_argument("--check", action="store_true", help="exit 1 when a generated file is stale")
    args = parser.parse_args(argv)
    if args.check:
        old = stale()
        for path in old:
            print(f"{path} differs from the layout spec: run python -m jarvis.layout_spec")
        return 1 if old else 0
    CSS.write_text(_with_generated(CSS.read_text(encoding="utf-8")), encoding="utf-8")
    font_metrics.WIDTHS.write_text(_widths(), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
